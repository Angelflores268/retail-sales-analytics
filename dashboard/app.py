"""Retail Sales Analytics dashboard with a self-contained SQLite backend.

The deployed app never needs an always-on Aiven / MySQL server.
Its archived dataset is generated by src/build_snapshot.py from the original
UCI Online Retail dataset using the original project's cleaning rules.
"""

from __future__ import annotations

import gzip
import os
import shutil
import sqlite3
import sys
from pathlib import Path

import pandas as pd
import plotly.express as px
import streamlit as st

ROOT = Path(__file__).resolve().parent.parent
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

ARCHIVE_PATH = ROOT / "data" / "retail_sales.sqlite.gz"
LOCAL_DB_PATH = ROOT / ".cache" / "retail_sales.sqlite"

st.set_page_config(page_title="Retail Sales Analytics", page_icon="📊", layout="wide")
st.title("Retail Sales Analytics Dashboard")
st.caption("Historical UK online retail transactions (2010–2011) · ETL + SQLite + Streamlit")


@st.cache_resource(show_spinner="Preparing sales database...")
def prepare_database() -> str:
    """Use bundled SQLite snapshot; download/build from UCI only as a fallback."""
    LOCAL_DB_PATH.parent.mkdir(parents=True, exist_ok=True)
    if LOCAL_DB_PATH.is_file() and LOCAL_DB_PATH.stat().st_size > 0:
        return str(LOCAL_DB_PATH)

    if ARCHIVE_PATH.is_file():
        temp = LOCAL_DB_PATH.with_suffix(".tmp")
        try:
            with gzip.open(ARCHIVE_PATH, "rb") as zipped, temp.open("wb") as target:
                shutil.copyfileobj(zipped, target)
            with sqlite3.connect(temp) as con:
                if con.execute("PRAGMA integrity_check").fetchone()[0] != "ok":
                    raise ValueError("The included database archive is corrupt")
            os.replace(temp, LOCAL_DB_PATH)
        finally:
            temp.unlink(missing_ok=True)
    else:
        # No archived dataset in GitHub yet. The first launch can bootstrap it.
        # For a fast, reliable public demo, use the build-snapshot GitHub Action
        # to commit data/retail_sales.sqlite.gz into the repository.
        from src.build_snapshot import build_snapshot
        build_snapshot(output=LOCAL_DB_PATH)

    return str(LOCAL_DB_PATH)


@st.cache_data(ttl=3600, show_spinner=False)
def sql_query(database: str, sql: str, country: str | None = None) -> pd.DataFrame:
    """Use a fresh read-only SQLite connection for each cached query."""
    with sqlite3.connect(f"file:{database}?mode=ro", uri=True) as conn:
        return pd.read_sql_query(sql, conn, params={"country": country})


try:
    database_path = prepare_database()
    with sqlite3.connect(f"file:{database_path}?mode=ro", uri=True) as connection:
        exists = connection.execute(
            "SELECT 1 FROM sqlite_master WHERE type='table' AND name='retail_sales'"
        ).fetchone()
    if not exists:
        raise RuntimeError("Snapshot does not contain a retail_sales table")
except Exception as exc:
    st.error("The sales dataset could not be prepared, so the dashboard cannot load yet.")
    st.warning(
        "To fix this permanently, run the repository's 'Build Retail Snapshot' "
        "GitHub Action. It downloads the public UCI dataset and saves a compressed "
        "SQLite file to the repository. No MySQL account is required."
    )
    with st.expander("Technical details"):
        st.exception(exc)
    st.stop()


countries = sql_query(
    database_path,
    "SELECT DISTINCT Country FROM retail_sales WHERE Country IS NOT NULL ORDER BY Country",
)
selected = st.sidebar.selectbox("Filter by country", ["All Countries"] + countries["Country"].tolist())
country = None if selected == "All Countries" else selected
where = "WHERE Country = :country" if country else ""
product_where = "WHERE Description IS NOT NULL" + (" AND Country = :country" if country else "")
customer_where = "WHERE CustomerID IS NOT NULL" + (" AND Country = :country" if country else "")

st.caption(f"Showing: {selected} · Positive, non-cancelled transactions with known customers")

kpi = sql_query(database_path, f"""
    SELECT
        COALESCE(ROUND(SUM(TotalPrice), 2), 0) AS total_revenue,
        COUNT(DISTINCT InvoiceNo) AS total_orders,
        COUNT(DISTINCT CustomerID) AS unique_customers,
        COALESCE(ROUND(SUM(TotalPrice) / NULLIF(COUNT(DISTINCT InvoiceNo), 0), 2), 0)
            AS average_order_value
    FROM retail_sales
    {where}
""", country).iloc[0]

m1, m2, m3, m4 = st.columns(4)
m1.metric("Total Revenue", f"£{float(kpi['total_revenue']):,.2f}")
m2.metric("Total Orders", f"{int(kpi['total_orders']):,}")
m3.metric("Unique Customers", f"{int(kpi['unique_customers']):,}")
m4.metric("Average Order Value", f"£{float(kpi['average_order_value']):,.2f}")

st.subheader("Monthly Revenue Trend")
monthly = sql_query(database_path, f"""
    SELECT substr(InvoiceDate, 1, 7) AS month, ROUND(SUM(TotalPrice), 2) AS revenue
    FROM retail_sales {where}
    GROUP BY substr(InvoiceDate, 1, 7)
    ORDER BY month
""", country)
if not monthly.empty:
    monthly["month"] = pd.to_datetime(monthly["month"] + "-01")
    fig = px.line(monthly, x="month", y="revenue", markers=True,
                  labels={"month": "Month", "revenue": "Revenue (£)"})
    st.plotly_chart(fig, use_container_width=True)
else:
    st.info("No transactions to chart.")

left, right = st.columns(2)
products = sql_query(database_path, f"""
    SELECT Description AS product, ROUND(SUM(TotalPrice), 2) AS revenue
    FROM retail_sales {product_where}
    GROUP BY Description ORDER BY revenue DESC LIMIT 10
""", country)
with left:
    st.subheader("Top Products by Revenue")
    if not products.empty:
        fig = px.bar(products, x="revenue", y="product", orientation="h",
                     labels={"revenue": "Revenue (£)", "product": "Product"})
        fig.update_layout(yaxis={"categoryorder": "total ascending"})
        st.plotly_chart(fig, use_container_width=True)
    else:
        st.info("No product data available.")

# Keep the country comparison global, exactly like the original project.
country_totals = sql_query(database_path, """
    SELECT Country AS country, ROUND(SUM(TotalPrice), 2) AS revenue
    FROM retail_sales WHERE Country IS NOT NULL
    GROUP BY Country ORDER BY revenue DESC LIMIT 10
""")
with right:
    st.subheader("Top Countries by Revenue · Global")
    if not country_totals.empty:
        fig = px.bar(country_totals, x="revenue", y="country", orientation="h",
                     labels={"revenue": "Revenue (£)", "country": "Country"})
        fig.update_layout(yaxis={"categoryorder": "total ascending"})
        st.plotly_chart(fig, use_container_width=True)
    else:
        st.info("No country data available.")

st.subheader("Top Customers by Revenue")
customers = sql_query(database_path, f"""
    SELECT CustomerID AS customer, ROUND(SUM(TotalPrice), 2) AS revenue
    FROM retail_sales {customer_where}
    GROUP BY CustomerID ORDER BY revenue DESC LIMIT 10
""", country)
if not customers.empty:
    customers["customer"] = customers["customer"].astype("int64").astype(str)
    fig = px.bar(customers, x="customer", y="revenue",
                 labels={"customer": "Customer ID", "revenue": "Revenue (£)"})
    st.plotly_chart(fig, use_container_width=True)
else:
    st.info("No customer data available.")

st.subheader("Revenue by Day of Week")
weekday = sql_query(database_path, f"""
    SELECT CAST(strftime('%w', InvoiceDate) AS INTEGER) AS weekday,
           ROUND(SUM(TotalPrice), 2) AS revenue
    FROM retail_sales {where}
    GROUP BY weekday ORDER BY weekday
""", country)
name_by_day = {0: "Sunday", 1: "Monday", 2: "Tuesday", 3: "Wednesday",
               4: "Thursday", 5: "Friday", 6: "Saturday"}
day_order = ["Monday", "Tuesday", "Wednesday", "Thursday", "Friday", "Saturday", "Sunday"]
if not weekday.empty:
    weekday["day"] = weekday["weekday"].map(name_by_day)
    weekday = (weekday.set_index("day")["revenue"].reindex(day_order, fill_value=0)
               .rename_axis("day").reset_index())
    fig = px.bar(weekday, x="day", y="revenue",
                 labels={"day": "Day", "revenue": "Revenue (£)"},
                 category_orders={"day": day_order})
    st.plotly_chart(fig, use_container_width=True)
else:
    st.info("No weekday data available.")

with st.expander("About the dataset and pipeline"):
    st.markdown(
        "The dashboard reads a **portable SQLite snapshot**, built from the public "
        "[UCI Online Retail dataset](https://archive.ics.uci.edu/dataset/352/online-retail). "
        "The ETL removes duplicate rows, cancellations, non-positive quantities/prices, "
        "and rows without customer or description information. The original MySQL ETL "
        "scripts are kept in the repository. Revenue is measured in GBP. "
        "**These are historical sample business data, not live sales.**"
    )
    st.caption("Source: D. Chen (2015), UCI Online Retail, CC BY 4.0 · doi:10.24432/C5BW33")
